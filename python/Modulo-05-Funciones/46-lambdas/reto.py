calcular_cuadrado = lambda numero: numero * numero
calcular_area_triangulo = lambda base, altura: (base * altura) / 2

resultado_cuadrado = calcular_cuadrado(5)
print("El cuadrado de 5 es:", resultado_cuadrado)

resultado_triangulo = calcular_area_triangulo(10, 4)
print("El área del triángulo (base 10, altura 4) es:", resultado_triangulo)
